# ========== ЗАПУСК БОТА ==========
def run_bot():
    """Запускает бота в отдельном потоке"""
    print("Бот запускается...")
    try:
        # Убираем старый вебхук и устанавливаем новый
        bot.remove_webhook()
        time.sleep(0.5)
        
        # URL вашего сервиса на Render
        render_url = os.environ.get('RENDER_EXTERNAL_URL')
        if render_url:
            webhook_url = f"{render_url}/"
            bot.set_webhook(url=webhook_url)
            print(f"Вебхук установлен: {webhook_url}")
        else:
            print("RENDER_EXTERNAL_URL не найден, использую polling")
            # Запасной вариант - polling (если запущено локально)
            bot.infinity_polling()
            
    except Exception as e:
        print(f"Ошибка при установке вебхука: {e}")
        # Если не получилось с вебхуком, пробуем polling
        bot.infinity_polling()

if __name__ == '__main__':
    # Запускаем бота в отдельном потоке
    bot_thread = threading.Thread(target=run_bot)
    bot_thread.daemon = True
    bot_thread.start()
    
    # Запускаем Flask-сервер
    port = int(os.environ.get('PORT', 5000))
    app.run(host='0.0.0.0', port=port)
