# ========== ВСЕ ВАШИ ФУНКЦИИ (create_main_menu, create_lessons_menu и т.д.) ==========
def create_main_menu():
    markup = types.InlineKeyboardMarkup(row_width=1)
    btn1 = types.InlineKeyboardButton("📚 Уроки 1-12", callback_data='section_1')
    btn2 = types.InlineKeyboardButton("📚 Уроки 13-24", callback_data='section_2')
    btn3 = types.InlineKeyboardButton("📚 Уроки 25-36", callback_data='section_3')
    markup.add(btn1, btn2, btn3)
    return markup

def create_lessons_menu(section):
    markup = types.InlineKeyboardMarkup(row_width=3)
    buttons = []
    
    start = (section - 1) * 12 + 1
    end = start + 11
    
    for i in range(start, end + 1):
        lesson_key = f'lesson_{i}'
        if lesson_key in homework:
            btn_text = f"{i}✅"
        else:
            btn_text = f"{i}⏳"
        
        btn = types.InlineKeyboardButton(btn_text, callback_data=f'lesson_{i}')
        buttons.append(btn)
    
    for i in range(0, len(buttons), 3):
        markup.add(*buttons[i:i+3])
    
    back_btn = types.InlineKeyboardButton("🔙 В главное меню", callback_data='main_menu')
    markup.add(back_btn)
    return markup

