# ========== ОБРАБОТЧИК КНОПОК ==========
@bot.callback_query_handler(func=lambda call: True)
def callback_handler(call):
    if call.data == 'main_menu':
        bot.edit_message_text(
            "Выберите нужный раздел:",
            call.message.chat.id,
            call.message.message_id,
            reply_markup=create_main_menu()
        )
    
    elif call.data.startswith('section_'):
        section = int(call.data.split('_')[1])
        bot.edit_message_text(
            f"📚 Раздел {section} (Уроки {(section-1)*12+1}-{section*12})\n✅ - готово, ⏳ - скоро",
            call.message.chat.id,
            call.message.message_id,
            reply_markup=create_lessons_menu(section)
        )
    
    elif call.data.startswith('lesson_'):
        lesson_num = int(call.data.split('_')[1])
        lesson_key = f'lesson_{lesson_num}'
        
        if lesson_key in homework:
            task_text = homework[lesson_key]['task']
            
            markup = types.InlineKeyboardMarkup()
            back_btn = types.InlineKeyboardButton(
                "🔙 К списку уроков", 
                callback_data=f"section_{(lesson_num-1)//12 + 1}"
            )
            main_menu_btn = types.InlineKeyboardButton("🔝 Главное меню", callback_data='main_menu')
            markup.add(back_btn, main_menu_btn)
            
            bot.edit_message_text(
                task_text,
                call.message.chat.id,
                call.message.message_id,
                reply_markup=markup,
                parse_mode='HTML'
            )
        else:
            bot.answer_callback_query(
                call.id, 
                "Этот урок пока в разработке! ⏳", 
                show_alert=True
            )

